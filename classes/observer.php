class observer {
    /**
     * Remove a deleted user's CPD activities and custom field answers, so no orphaned personal data remains.
     *
     * @param \core\event\user_deleted $event
     */
    public static function user_deleted(\core\event\user_deleted $event): void {
        (new manager())->delete_user_data((int)$event->objectid);
    }
}
